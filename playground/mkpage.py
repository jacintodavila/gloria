def agent_source(name, kb, main):
    """Self-contained .pl for an agent: module header + .kb + .main."""
    outdir = os.path.join(ROOT, 'src', 'agents', name)
    parts = ['%% Gloria agent %s (generated by playground/mkpage.py).\n' % name,
             '%% Do not edit: regenerate from src/agents/%s/ instead.\n' % name,
             ':- module(%s, []).\n' % name]
    for fn in (kb, main):
        path = os.path.join(outdir, fn)
        with open(path, encoding='utf-8') as f:
            text = f.read()
        parts.append('\n%%%% %s %s\n' % ('%' * 30, fn))
        parts.append(text if text.endswith('\n') else text + '\n')
    return ''.join(parts)


def js_str(s):
    """Escape a string as a JavaScript template literal."""
    return s.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')


def examples_menu(agents):
    """JS list of Examples-menu entries, as ?code=...&ext=.pl links."""
    items = ["      // Gloria agents (embedded in the page, no extra fetch)"]
    items.append("      { k: '', n: '<div style=\"font-weight: bold\">Gloria agents</div>' },")
    for name, title, _kb, _main in agents:
        url = 'gloria.html?ext=.pl&code=' + quote(agent_source(*find(name)), safe='')
        n = ('<a href="%s" onclick="event.stopPropagation()">'
             '&#x1F4C4; %s</a>') % (url.replace('&', '&amp;'), title)
        items.append("      { k: '', n: '%s' }," % n.replace("'", "\\'"))
    return items


def run_menu(agents):
    """JSON list of "Run agent" menu entries (query + display HTML).

    Selecting an entry inserts its `q' (a complete Prolog query) into the
    top level; the user then presses Enter to run it.  Header entries have
    an empty key and query and are ignored by the click handler.
    """
    items = [
        {'k': '', 'q': '',
         'n': ('<div style="font-weight: bold">Load the agent first '
               '(Examples &rarr; agent, then Load &#9654;), '
               'then choose a query</div>')},
        {'k': '', 'q': '',
         'n': ('<div style="font-style: italic">The query is inserted in '
               'the top level; press Enter to run it.</div>')},
    ]
    for name, title, _kb, _main in agents:
        items.append({
            'k': '', 'q': '',
            'n': ('<div style="font-weight: bold; padding-top: 6px">%s</div>'
                  % html.escape(title)),
        })
        for i, (label, t, obs) in enumerate(AGENT_RUNS.get(name, [])):
            query = 'prolog_agent(%s, %d, 400, %s, Actions).' % (
                name, t, obs)
            display = ('<b>%s</b> &mdash; %s<br>'
                       '<span style="font-family: monospace; '
                       'font-size: 0.9em">%s</span>') % (
                           html.escape(title), html.escape(label),
                           html.escape(query))
            items.append({
                'k': 'run-%s-%d' % (name, i),
                'q': query,
                'n': display,
            })
    return json.dumps(items, ensure_ascii=False, indent=2)


def find(name):
    for n, _t, kb, main in AGENTS:
        if n == name:
            return (n, kb, main)
    raise KeyError(name)


SPLASH_HEADER = """\
%% ---------------------------------------------------------------- Gloria agent
%%
%% This editor holds a self-contained Gloria agent:
%%
%%   :- module(<agent>, ...).   the agent id (change it to rename the agent)
%%   abd/1, observable/1, ...   the agent configuration
%%   if_/2, def/2, ...          the knowledge base (goals and beliefs)
%%
%% Press "Load" to upload this code to the engine and build the agent.
%% Then run a reasoning step in the top level below, for example:
%%
%%   ?- prolog_agent(enclosure, 0, 400, [time_day(am), it_is(sunny)], Actions).
%%
%% or a single debug step, which also returns the pending goals:
%%
%%   ?- gloria_step(enclosure, 0, 400, [time_day(am), it_is(sunny)], Ng, Og, Actions).
%%
%% Edit the rules below, press "Load" again, and re-run.
%% --------------------------------------------------------------------------
"""


def splash_code(agents):
    name = agents[0][0]
    src = agent_source(*find(name))
    # Drop the generated-file marker: the editor is meant to be edited.
    src = re.sub(r'^%% (Gloria agent .*|Do not edit:.*)\n', '', src, flags=re.M)
    return SPLASH_HEADER + '\n' + src


PAGE = r"""\
<!DOCTYPE html>
<html>
  <head>
    <meta charset="utf-8">
    <title>Gloria playground (reactive agents)</title>
    <link rel="stylesheet" href="/css/lpdoc.css" type="text/css"/>
    <link rel="stylesheet" href="/playground/css/ciao_playground.css" type="text/css"/>
    <link rel="stylesheet" href="/playground/css/ciao_menu.css" type="text/css"/>
    <script>
      var playgroundCfg = {
        title: "Gloria playground (reactive agents)",
        window_layout: ['E','T'],
        // localStorage key (do not collide with the main playground)
        storage_key: 'gloria_code',
        // The editor holds a self-contained Gloria agent (see agents/*.pl)
        splash_code: { '.pl': `%(splash)s` },
        splash_dialog: false,
        // Never amend the agent source: the module directive names the agent
        amend_on_save: false,
        // Reload the agent only on demand (button), not on every edit
        on_the_fly: false,
        //
        has_new_button: true,
        has_file_button: true,
        has_load_button: true,
        has_share_button: true,
        has_layout_button: true,
        has_examples_button: true,
        //
        has_ext_mode_button: false,
        has_doc_button: false,
        has_debug_button: false,
        has_run_tests_button: false,
        has_acheck_button: false,
        has_spec_button: false,
        has_browse_analysis_opts_button: false,
        has_toggle_presentation_button: false,
        has_toggle_on_the_fly_button: false,
        with_github_stars: false,
        //
        example_list: [
%(examples)s
        ]
      };

      var toplevelCfg = {
        statistics: false,
        // (defaults are ciaowasm, core, builder)
        init_bundles: ['ciaowasm', 'core', 'builder', 'gloria'],
        // Load the Gloria engine and the query-rewriting helper into the
        // worker by their *source path*, not as `library(...)'.
        //
        // The engine predicates (`prolog_agent/5', `load_agent_code/1', ...)
        // live in the single `gloria' module, and the top level runs in
        // `user': module-qualifying them from `user' fails with "Bad module
        // qualification", and `use_module(library(gloria/gloria))' cannot
        // be resolved inside the prebuilt wasm engine (its bundle registry
        // does not carry the gloria library aliases).  The `.pl' sources
        // *are* in the worker VFS, so importing them by path works and is
        // what makes the engine usable from the top level.
        //
        // NOTE: `%(srcpath)s' is the bundle's source directory as seen
        // inside the worker; it is written by mkpage.py from the workspace
        // location (see `bundle_srcdir' in the bundle metadata).
        init_queries: [
          'use_module(engine(internals), [reload_bundleregs/0])',
          'use_module(library(classic/classic_predicates))',
          "use_module('%(srcpath)s/ciao/gloria/src/gloria.pl')",
          "use_module('%(srcpath)s/ciao/gloria/src/gloria_playground.pl'," +
            ' [disguise_trans_query/3])'
        ],
        // 'use_module': upload the editor before loading modules.
        // 'load_agent_code': upload the editor before building the agent.
        special_query: {
          'use_module': { read_code: true, mark_errs: true },
          'load_agent_code': { read_code: true, mark_errs: true }
        },
        // Build the agent from the uploaded editor file (path '/<agent>.pl',
        // where <agent> comes from the module directive).  `load_agent_code'
        // is a Gloria entry point, so the query wrapper below turns it into
        // `gloria:load_agent_code(...)' while `special_query' above still
        // matches the original functor and uploads the editor first.
        custom_load_query: m => "load_agent_code('" + m + "')",
        // User queries go in as they are; the page wraps them for Prolog
        // rewriting (see pg_rewrite_goal).
        custom_run_query: q => q
      };
    </script>
    <script> var lpdocPG='playground'; </script>
    <script src="/js/lpdoc.js"></script> <!-- LPdoc UI -->
    <script>
      // --------------------------------------------------------------------
      // Let Prolog rewrite the page's top-level queries.
      //
      // The playground's top level runs in `user', and the Gloria engine is
      // a single Ciao module, so `prolog_agent(...)' typed there is unknown
      // and `gloria:prolog_agent(...)' is a bad qualification.  Rather than
      // importing the whole engine into `user', we ask Prolog to rewrite
      // each user query inside the `gloria' scope:
      //
      //     disguise_trans_query(Query, _, Q), Q
      //
      // `disguise_trans_query/3' rewrites Gloria goals inside out
      // (load_agent_code / prolog_agent / gloria_step -> gloria:...) and
      // leaves anything else unchanged, so ordinary top-level use is
      // unaffected.
      //
      // The interception point is ToplevelProc.prototype.trans_query,
      // because run_query calls it for *every* query (user and load) and it
      // is where toplevelCfg.custom_run_query and toplevelCfg.special_query
      // are applied -- patching here means the special_query actions
      // (read_code -> upload the editor to the worker) still fire while the
      // *original* functor (`load_agent_code', `prolog_agent', ...) is
      // matched, and the rewriting then only has to change tr.q.
      //
      // ciao-prolog.js is imported asynchronously by lpdoc.js, so the patch
      // is installed as soon as ToplevelProc shows up (it must not be
      // installed at DOMContentLoaded: the class does not exist yet, which
      // is exactly what made the previous attempt die with a ReferenceError).
      // --------------------------------------------------------------------
      function pg_install_rewriting() {
        if (typeof ToplevelProc === 'undefined') return false;
        if (ToplevelProc.prototype.pg_rewriting_installed) return true;
        const orig_trans_query = ToplevelProc.prototype.trans_query;
        ToplevelProc.prototype.trans_query = async function (query) {
          const tr = await orig_trans_query.call(this, query);
          // (init_queries/use_module etc. keep their original goal; only the
          // user-facing Gloria goals and the load query are wrapped)
          const q = String(tr.q).trim();
          if (q !== '') tr.q = pg_rewrite_goal(q);
          return tr;
        };
        ToplevelProc.prototype.pg_rewriting_installed = true;
        return true;
      }
      // The rewriting wrapper: disguise_trans_query/3 rewrites *inside* the
      // `gloria' scope and returns Q unchanged when the query is not Gloria's.
      // (Both `gloria' and `disguise_trans_query/3' are loaded by
      // toplevelCfg.init_queries, so nothing has to be imported per query.)
      //
      // The playground hands run_query a query *without* a final period
      // (`Comint.#current_input` strips it, and `load_code` never adds one),
      // and `query_one_begin` wants exactly that: a period must NOT be
      // appended here or the worker answers "SYNTAX ERROR: Malformed query".
      // Strip a period defensively (a directly-issued query may carry one)
      // but never add one.
      function pg_rewrite_goal(q) {
        let body = String(q).trim();
        if (body.endsWith('.')) body = body.slice(0, -1).trim();
        return 'disguise_trans_query((' + body + '), _, Q), Q';
      }

      // --------------------------------------------------------------------
      // "Run agent" menu.
      //
      // The page exposes the Prolog query syntax explicitly instead of
      // hiding it behind a button: choosing an entry inserts a complete
      // query into the top-level input, so it can be inspected, edited
      // (e.g. to change the observations or the time) and finally run with
      // Enter.  The queries are generated by playground/mkpage.py from the
      // same sample observations used by the ALD notebooks and tests.
      // --------------------------------------------------------------------
      const gloriaQueries = %(queries)s;

      async function pg_insert_toplevel_query(pg, q) {
        const c = pg.toplevel;
        if (c === null || c.editor === undefined) return;
        const cproc = pg.cproc;
        if (cproc.state === QueryState.RUNNING) return; // busy
        if (cproc.state === QueryState.VALIDATING) {
          // A previous query is waiting for "more solutions?".  Accept its
          // last solution first, so the query below goes to a fresh prompt.
          await c.treat_enter();
          while (cproc.state !== QueryState.READY) {
            await new Promise(resolve => setTimeout(resolve, 25));
          }
        }
        if (cproc.state !== QueryState.READY) return;
        const editor = c.editor;
        const model = editor.getModel();
        c.move_to_end();
        let ln = model.getLineCount();
        let line = model.getLineContent(ln);
        if (!line.startsWith(c.prompt)) {
          // No prompt yet (first use): start a new input line.
          c.display(line === '' ? c.prompt : '\n' + c.prompt);
          ln = model.getLineCount();
          line = model.getLineContent(ln);
        }
        const start = c.prompt.length + 1;
        // Replace whatever is on the current prompt line (without running).
        editor.executeEdits('gloria-run', [{
          range: new monaco.Range(ln, start, ln, line.length + 1),
          text: q
        }]);
        editor.setPosition({ lineNumber: ln, column: start + q.length });
        editor.focus();
        c.reveal_end();
      }

      function pg_install_run_menu(pg) {
        if (pg.gloria_run_menu_installed) return;
        pg.gloria_run_menu_installed = true;
        if (!pg.menu_el) return;
        // DropdownButton appends to its first argument; use a holder so the
        // menu can be inserted before the right-hand (share/etc.) buttons.
        const holder = document.createElement('div');
        const dropdown = new DropdownButton(
          holder,
          "Insert a Prolog query to run an agent (load the agent first)",
          elem_from_str("<span>Run agent</span>"),
          gloriaQueries,
          value => {
            const item = gloriaQueries.find(x => x.k === value);
            if (item !== undefined && item.q !== '') {
              pg_insert_toplevel_query(pg, item.q).catch(console.error);
            }
          });
        dropdown.btn_el.classList.add('menu-button');
        dropdown.btn_el.style.height = '100%%';
        const dd_el = holder.firstElementChild;
        const right_el = pg.menu_el.querySelector('.right-menu');
        if (right_el !== null) {
          pg.menu_el.insertBefore(dd_el, right_el);
        } else {
          pg.menu_el.appendChild(dd_el);
        }
      }

      function pg_install_run_menu_hook() {
        if (typeof PGCell === 'undefined') return false;
        if (typeof DropdownButton === 'undefined') return false;
        if (!PGCell.prototype.pg_run_menu_hooked) {
          const orig_setup = PGCell.prototype.setup;
          PGCell.prototype.setup = async function (...args) {
            // PGCell.setup sets this.menu_el before its first await.
            const res = orig_setup.apply(this, args);
            if (!this.is_R && this.menu_el) pg_install_run_menu(this);
            return res;
          };
          PGCell.prototype.pg_run_menu_hooked = true;
        }
        // Fallback when the cell was already set up before this hook was
        // installed (main_doc.pgset is set by PGSet.attach_main_doc).
        if (typeof main_doc !== 'undefined' && main_doc !== null &&
            main_doc.pgset !== undefined) {
          for (const cell of main_doc.pgset.cells) {
            if (!cell.is_R && cell.menu_el) pg_install_run_menu(cell);
          }
        }
        return true;
      }

      window.addEventListener('DOMContentLoaded', () => {
        // ToplevelProc (query rewriting) and PGCell (Run agent menu) are
        // defined by scripts loaded asynchronously after DOMContentLoaded.
        const timer = setInterval(() => {
          const rewriting = pg_install_rewriting();
          const menu = pg_install_run_menu_hook();
          if (rewriting && menu) clearInterval(timer);
        }, 50);
      });
    </script>
  </head>
  <body></body>
</html>
"""


def main():
    agents = []
    for name, title, kb, main_ in AGENTS:
        agents.append((name, title, kb, main_))
        # sanity: sources exist
        for fn in (kb, main_):
            p = os.path.join(ROOT, 'src', 'agents', name, fn)
            if not os.path.exists(p):
                sys.exit('mkpage.py: missing %s' % p)

    outdir = os.path.join(ROOT, 'playground', 'agents')
    os.makedirs(outdir, exist_ok=True)
    for name, _title, kb, main_ in agents:
        with open(os.path.join(outdir, name + '.pl'), 'w', encoding='utf-8') as f:
            f.write(agent_source(name, kb, main_))

    page = PAGE % {
        'splash': js_str(splash_code(agents)),
        'examples': '\n'.join(examples_menu(agents)),
        'queries': run_menu(agents),
        'srcpath': BUNDLE_SRCDIR,
    }
    path = os.path.join(ROOT, 'playground', 'gloria.html')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(page)
    print('wrote %s and playground/agents/*.pl' % path)


if __name__ == '__main__':
    main()
