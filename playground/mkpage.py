#!/usr/bin/env python3
"""Generate the Gloria browser playground page.

Builds `playground/gloria.html` (a Ciao `ciao_playground` page) from the
agent knowledge bases in `src/agents/`.

For every agent it produces a *self-contained* Ciao source file in
`playground/agents/<name>.pl`: a module directive that names the agent
followed by the contents of its `.kb` (the knowledge base: if_/2 goals
and def/2 beliefs) and of its `.main` (the configuration: abd/1,
observable/1, for_testing_only/1, ...).  The Gloria loader reads both
kinds of clause from a single file, so this is all a playground editor
needs -- and it is what the user gets to edit and reload.

Those files are embedded in the page as `?code=...&ext=.pl` links in the
Examples menu (see `code_from_URL` / `code_from_URL_link` in
ciao_playground.js), so no extra HTTP or bundle access is needed.

Run from the repository root:  python3 playground/mkpage.py
"""

import os
import re
import sys
from urllib.parse import quote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (agent id, human name, knowledge base file, configuration file)
# The agent id is what load_agent_code/1 will derive from the file name.
AGENTS = [
    ('enclosure',   'Enclosure (windows and doors)', 'enclosure.kb',   'enclosure.main'),
    ('mylamp',      'MyLamp (motion light)',         'mylamp.kb',      'mylamp.main'),
    ('burocratin',  'Burocratin (bureaucrat)',       'burocratin.kb',  'burocratin.main'),
    ('gerente',     'Gerente (queue manager)',       'gerente.kb',     'gerente.main'),
    ('arch',        'Arch (abduction example)',      'ex-arch.kb',     'ex-arch.main'),
    ('rentin',      'Rentin (opportunist)',          'rentin.kb',      'rentin.main'),
]

DEFAULT_AGENT = 'enclosure'


def agent_source(name, kb, main):
    """Self-contained .pl for an agent: module header + .kb + .main."""
    outdir = os.path.join(ROOT, 'src', 'agents', name)
    parts = ['%% Gloria agent %s (generated by playground/mkpage.py).\n' % name,
             '%% Do not edit: regenerate from src/agents/%s/ instead.\n' % name,
             ':- module(%s, []).\n' % name]
    for fn in (kb, main):
        path = os.path.join(outdir, fn)
        with open(path, encoding='utf-8') as f:
            text = f.read()
        parts.append('\n%%%% %s %s\n' % ('%' * 30, fn))
        parts.append(text if text.endswith('\n') else text + '\n')
    return ''.join(parts)


def js_str(s):
    """Escape a string as a JavaScript template literal."""
    return s.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')


def examples_menu(agents):
    """JS list of Examples-menu entries, as ?code=...&ext=.pl links."""
    items = ["      // Gloria agents (embedded in the page, no extra fetch)"]
    items.append("      { k: '', n: '<div style=\"font-weight: bold\">Gloria agents</div>' },")
    for name, title, _kb, _main in agents:
        url = 'gloria.html?ext=.pl&code=' + quote(agent_source(*find(name)), safe='')
        n = ('<a href="%s" onclick="event.stopPropagation()">'
             '&#x1F4C4; %s</a>') % (url.replace('&', '&amp;'), title)
        items.append("      { k: '', n: '%s' }," % n.replace("'", "\\'"))
    return items


def find(name):
    for n, _t, kb, main in AGENTS:
        if n == name:
            return (n, kb, main)
    raise KeyError(name)


SPLASH_HEADER = """\
%% ---------------------------------------------------------------- Gloria agent
%%
%% This editor holds a self-contained Gloria agent:
%%
%%   :- module(<agent>, ...).   the agent id (change it to rename the agent)
%%   abd/1, observable/1, ...   the agent configuration
%%   if_/2, def/2, ...          the knowledge base (goals and beliefs)
%%
%% Press "Load" to upload this code to the engine and build the agent.
%% Then run a reasoning step in the top level below, for example:
%%
%%   ?- prolog_agent(enclosure, 0, 400, [time_day(am), it_is(sunny)], Actions).
%%
%% or a single debug step, which also returns the pending goals:
%%
%%   ?- gloria_step(enclosure, 0, 400, [time_day(am), it_is(sunny)], Ng, Og, Actions).
%%
%% Edit the rules below, press "Load" again, and re-run.
%% --------------------------------------------------------------------------
"""


def splash_code(agents):
    name = agents[0][0]
    src = agent_source(*find(name))
    # Drop the generated-file marker: the editor is meant to be edited.
    src = re.sub(r'^%% (Gloria agent .*|Do not edit:.*)\n', '', src, flags=re.M)
    return SPLASH_HEADER + '\n' + src


PAGE = """\
<!DOCTYPE html>
<html>
  <head>
    <meta charset="utf-8">
    <title>Gloria playground (reactive agents)</title>
    <link rel="stylesheet" href="/css/lpdoc.css" type="text/css"/>
    <link rel="stylesheet" href="/playground/css/ciao_playground.css" type="text/css"/>
    <link rel="stylesheet" href="/playground/css/ciao_menu.css" type="text/css"/>
    <script>
      var playgroundCfg = {
        title: "Gloria playground (reactive agents)",
        window_layout: ['E','T'],
        // localStorage key (do not collide with the main playground)
        storage_key: 'gloria_code',
        // The editor holds a self-contained Gloria agent (see agents/*.pl)
        splash_code: { '.pl': `%(splash)s` },
        splash_dialog: false,
        // Never amend the agent source: the module directive names the agent
        amend_on_save: false,
        // Reload the agent only on demand (button), not on every edit
        on_the_fly: false,
        //
        has_new_button: true,
        has_file_button: true,
        has_load_button: true,
        has_share_button: true,
        has_layout_button: true,
        has_examples_button: true,
        //
        has_ext_mode_button: false,
        has_doc_button: false,
        has_debug_button: false,
        has_run_tests_button: false,
        has_acheck_button: false,
        has_spec_button: false,
        has_browse_analysis_opts_button: false,
        has_toggle_presentation_button: false,
        has_toggle_on_the_fly_button: false,
        with_github_stars: false,
        //
        example_list: [
%(examples)s
        ]
      };

      var toplevelCfg = {
        statistics: false,
        // (defaults are ciaowasm, core, builder)
        init_bundles: ['ciaowasm', 'core', 'builder', 'gloria'],
        init_queries: [
          'use_module(engine(internals), [reload_bundleregs/0])',
          'use_module(library(classic/classic_predicates))',
          'use_module(library(gloria/gloria))'
        ],
        // 'use_module': upload the editor before loading modules.
        // 'load_agent_code': upload the editor before building the agent
        // (the functor is what trans_query/2 matches, module prefix aside).
        special_query: {
          'use_module': { read_code: true, mark_errs: true },
          'load_agent_code': { read_code: true, mark_errs: true }
        },
        // Build the agent from the uploaded editor file. Its path is
        // '/<agent>.pl', where <agent> comes from the module directive.
        custom_load_query: m => "gloria:load_agent_code('" + m + "')"
      };
    </script>
    <script> var lpdocPG='playground'; </script>
    <script src="/js/lpdoc.js"></script> <!-- LPdoc UI -->
  </head>
  <body></body>
</html>
"""


def main():
    agents = []
    for name, title, kb, main_ in AGENTS:
        agents.append((name, title, kb, main_))
        # sanity: sources exist
        for fn in (kb, main_):
            p = os.path.join(ROOT, 'src', 'agents', name, fn)
            if not os.path.exists(p):
                sys.exit('mkpage.py: missing %s' % p)

    outdir = os.path.join(ROOT, 'playground', 'agents')
    os.makedirs(outdir, exist_ok=True)
    for name, _title, kb, main_ in agents:
        with open(os.path.join(outdir, name + '.pl'), 'w', encoding='utf-8') as f:
            f.write(agent_source(name, kb, main_))

    page = PAGE % {
        'splash': js_str(splash_code(agents)),
        'examples': '\n'.join(examples_menu(agents)),
    }
    path = os.path.join(ROOT, 'playground', 'gloria.html')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(page)
    print('wrote %s and playground/agents/*.pl' % path)


if __name__ == '__main__':
    main()
